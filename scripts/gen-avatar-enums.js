import assert from 'node:assert/strict';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const manifest = JSON.parse(await readFile(join(root, 'avatar-art/manifest.json'), 'utf8'));
const check = process.argv.includes('--check');
const parts = Object.fromEntries(manifest.slots.map(slot => [slot.slot, slot.parts.map(part => part.id)]));
const layers = manifest.slots.map(slot => ({ slot: slot.slot, zOrder: slot.zOrder,
  parts: Object.fromEntries(slot.parts.map(part => [part.id, { tintable: part.tintable }])) }));
assert.deepEqual(parts.hairBack, parts.hairFront, 'front and back hair must share ids');
const data = { version: manifest.version, size: manifest.size, parts, layers,
  palette: Object.fromEntries(manifest.palette.map(color => [color.id, color.hex])),
  skinTones: Object.fromEntries(manifest.skinTones.map(color => [color.id, color.hex])) };
const json = JSON.stringify(data, null, 2);
const server = `// Generated by scripts/gen-avatar-enums.js. Do not edit.\nexport const AVATAR_PARTS = Object.freeze(${json});\n`;
const client = `/* global window */\n// Generated by scripts/gen-avatar-enums.js. Do not edit.\nwindow.TablemateAvatarParts = Object.freeze(${json});\n`;
const csArray = (name, values) => `    public static readonly string[] ${name} = { ${values.map(value => `"${value}"`).join(', ')} };`;
const pascal = word => word[0].toUpperCase() + word.slice(1);
const cs = [
  '// Generated by scripts/gen-avatar-enums.js. Do not edit.',
  'using System;',
  'public static class AvatarParts',
  '{',
  `    public const int ManifestVersion = ${manifest.version};`,
  `    public const int Size = ${manifest.size};`,
  csArray('Slots', manifest.slots.map(slot => slot.slot)),
  `    public static readonly int[] ZOrders = { ${manifest.slots.map(slot => slot.zOrder).join(', ')} };`,
  ...manifest.slots.map(slot => csArray(pascal(slot.slot), slot.parts.map(part => part.id))),
  csArray('PaletteIds', manifest.palette.map(color => color.id)),
  csArray('PaletteHex', manifest.palette.map(color => color.hex)),
  csArray('SkinIds', manifest.skinTones.map(color => color.id)),
  csArray('SkinHex', manifest.skinTones.map(color => color.hex)),
  '    public static bool Has(string[] values, string value) => Array.IndexOf(values, value) >= 0;',
  '}', ''
].join('\n');
for (const [relative, content] of [
  ['src/avatar-parts.js', server], ['public/avatar-parts.js', client],
  ['unity/AvatarCreator/Assets/Scripts/AvatarParts.cs', cs]
]) {
  const path = join(root, relative);
  if (check) assert.equal(await readFile(path, 'utf8'), content, `${relative} is stale`);
  else { await mkdir(dirname(path), { recursive: true }); await writeFile(path, content); }
}
process.stdout.write(`${check ? 'Checked' : 'Generated'} avatar enums for server, browser and Unity.\n`);
